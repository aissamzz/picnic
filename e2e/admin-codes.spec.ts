import { expect, test } from "@playwright/test";
import { adminIssueCode, adminPage, createRestaurant, displayPhone, logIn, rand, randomPhone, signUp } from "./helpers";

test("owner verifies their phone with a code generated by the admin", async ({ page, browser }) => {
  const phone = randomPhone();
  await signUp(page, phone);
  await createRestaurant(page, `Verif ${rand()}`);

  await page.goto("/app/compte");
  await expect(page.getByText("Non vérifié")).toBeVisible();
  await page.getByRole("link", { name: "Vérifier mon numéro" }).click();
  await page.getByRole("button", { name: "Demander l'appel" }).click();
  await expect(page.getByText("Nous allons vous appeler")).toBeVisible();

  const admin = await adminPage(browser);
  const code = await adminIssueCode(admin, displayPhone(phone));
  expect(code).toMatch(/^\d{6}$/);

  // The owner's screen switches to the code form with the 2-minute timer.
  await expect(page.getByText("Saisissez le code")).toBeVisible({ timeout: 15_000 });
  await expect(page.getByText(/^[12]:\d\d$/)).toBeVisible();
  const wrong = code === "123456" ? "654321" : "123456";
  await page.getByLabel("Code à 6 chiffres").fill(wrong);
  await page.getByRole("button", { name: "Valider" }).click();
  await expect(page.getByText("Code incorrect.")).toBeVisible();
  await page.getByLabel("Code à 6 chiffres").fill(code);
  await page.getByRole("button", { name: "Valider" }).click();
  await expect(page.getByText("Votre numéro est vérifié.")).toBeVisible();

  await page.goto("/app/compte");
  await expect(page.getByText("Vérifié", { exact: true })).toBeVisible();
  await admin.context().close();
});

test("forgot password: admin calls, user resets with the code", async ({ page, browser }) => {
  const phone = randomPhone();
  await signUp(page, phone, "old-pass-123");
  await page.context().clearCookies();

  await page.goto("/mot-de-passe-oublie");
  await page.getByLabel("Numéro de téléphone").fill(randomPhone());
  await page.getByRole("button", { name: "Demander un code" }).click();
  await expect(page.getByText("Aucun compte avec ce numéro.")).toBeVisible();

  await page.getByLabel("Numéro de téléphone").fill(phone);
  await page.getByRole("button", { name: "Demander un code" }).click();
  await expect(page.getByText("Nous allons vous appeler")).toBeVisible();

  const admin = await adminPage(browser);
  const code = await adminIssueCode(admin, displayPhone(phone));
  await admin.context().close();

  await expect(page.getByText("Saisissez le code")).toBeVisible({ timeout: 15_000 });
  await page.getByLabel("Code à 6 chiffres").fill(code);
  await page.getByLabel("Nouveau mot de passe", { exact: true }).fill("new-pass-456");
  await page.getByLabel("Confirmez le nouveau mot de passe").fill("new-pass-456");
  await page.getByRole("button", { name: "Changer le mot de passe" }).click();
  await expect(page).toHaveURL(/\/app/);

  // Old password no longer works, new one does.
  await page.context().clearCookies();
  await logIn(page, phone, "old-pass-123");
  await expect(page.getByText("Numéro ou mot de passe incorrect.")).toBeVisible();
  await logIn(page, phone, "new-pass-456");
  await expect(page).toHaveURL(/\/app/);
});
