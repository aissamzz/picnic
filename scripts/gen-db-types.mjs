#!/usr/bin/env node
// Generates lib/supabase/types.ts from the JSON emitted by
// supabase/tests/local/introspect.sql (see `pnpm db:types`).
// Output follows the shape of `supabase gen types typescript`, so the file
// can be replaced by the official generator at any time.
import { readFileSync, writeFileSync } from "node:fs";

const schema = JSON.parse(readFileSync(process.argv[2], "utf8"));
const out = process.argv[3];
const enums = schema.enums ?? {};

const scalar = (udt) => {
  if (enums[udt]) return `Database["public"]["Enums"]["${udt}"]`;
  switch (udt) {
    case "int2": case "int4": case "int8": case "float4": case "float8": case "numeric": return "number";
    case "bool": return "boolean";
    case "json": case "jsonb": return "Json";
    case "void": return "undefined";
    default: return "string"; // uuid, text, timestamptz, date, time, citext...
  }
};
const colType = (c) => {
  const base = c.udt.startsWith("_") ? `${scalar(c.elem ?? c.udt.slice(1))}[]` : scalar(c.udt);
  return c.nullable ? `${base} | null` : base;
};

const lines = [];
const w = (s = "") => lines.push(s);
w("// Generated by scripts/gen-db-types.mjs. Do not edit by hand.");
w("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
w();
w("export type Database = {");
w("  public: {");
for (const [section, kind] of [["Tables", "table"], ["Views", "view"]]) {
  w(`    ${section}: {`);
  for (const t of schema.tables.filter((t) => t.kind === kind)) {
    w(`      ${t.name}: {`);
    w("        Row: {");
    for (const c of t.columns) w(`          ${c.name}: ${colType(c)};`);
    w("        };");
    if (kind === "table") {
      w("        Insert: {");
      for (const c of t.columns.filter((c) => !c.generated))
        w(`          ${c.name}${c.nullable || c.has_default ? "?" : ""}: ${colType(c)};`);
      w("        };");
      w("        Update: {");
      for (const c of t.columns.filter((c) => !c.generated)) w(`          ${c.name}?: ${colType(c)};`);
      w("        };");
    }
    const rels = t.relationships ?? [];
    if (!rels.length) w("        Relationships: [];");
    else {
      w("        Relationships: [");
      for (const r of rels) {
        w("          {");
        w(`            foreignKeyName: ${JSON.stringify(r.name)};`);
        w(`            columns: ${JSON.stringify(r.columns)};`);
        w(`            isOneToOne: ${r.one_to_one};`);
        w(`            referencedRelation: ${JSON.stringify(r.ref_table)};`);
        w(`            referencedColumns: ${JSON.stringify(r.ref_columns)};`);
        w("          },");
      }
      w("        ];");
    }
    w("      };");
  }
  w("    };");
}
w("    Functions: {");
for (const f of schema.functions ?? []) {
  const args = (f.args ?? []).filter((a) => a.name);
  w(`      ${f.name}: {`);
  w(args.length ? `        Args: { ${args.map((a) => `${a.name}${a.optional ? "?" : ""}: ${scalar(a.udt)}`).join("; ")} };` : "        Args: never;");
  let ret;
  if (f.out_cols?.length) ret = `{ ${f.out_cols.map((c) => `${c.name}: ${scalar(c.udt)}`).join("; ")} }[]`;
  else ret = scalar(f.returns) + (f.returns_set ? "[]" : "");
  w(`        Returns: ${ret};`);
  w("      };");
}
w("    };");
w("    Enums: {");
for (const [name, values] of Object.entries(enums)) w(`      ${name}: ${values.map((v) => JSON.stringify(v)).join(" | ")};`);
w("    };");
w("    CompositeTypes: Record<string, never>;");
w("  };");
w("};");
w();
w('type PublicSchema = Database["public"];');
w('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];');
w('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];');
w('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];');
w('export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];');
writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${out}`);
